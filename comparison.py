
a = 10
b = 5

print(f"Values: a = {a}, b = {b}\n")

# 1. Equal to (==)
print(f"a == b : {a == b}")  # False

# 2. Not equal to (!=)
print(f"a != b : {a != b}")  # True

# 3. Greater than (>)
print(f"a > b  : {a > b}")   # True

# 4. Less than (<)
print(f"a < b  : {a < b}")   # False

# 5. Greater than or equal to (>=)
print(f"a >= b : {a >= b}")  # True

# 6. Less than or equal to (<=)
print(f"a <= b : {a <= b}")  # False

print("-" * 30)

# Bonus: Chained comparison example
x = 10
y = 20
z = 30
print(f"Chained comparison (x < y < z): {x < y < z}")  # True